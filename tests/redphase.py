def apply(src, old, new):
    pairs = old if isinstance(old, tuple) else ((old, new),)
    for o, n in pairs:
        if src.count(o) < 1:
            return None
        src = src.replace(o, n)  # every site of the same feature
    return src


def make_copy(root, name):
    dst = os.path.join(root, name)
    os.mkdir(dst)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    shutil.copytree(BIN, os.path.join(dst, "bin"), ignore=ignore)
    shutil.copytree(os.path.join(SRC, "tests"), os.path.join(dst, "tests"), ignore=ignore)
    return dst


def run_one(tree, test):
    env = dict(os.environ)
    env["C_LEAN_BIN_DIR"] = os.path.join(tree, "bin")
    try:
        p = subprocess.run([sys.executable, os.path.join(tree, "tests", "test_c_lean.py"),
                            "Case." + test],
                           capture_output=True, text=True, cwd=tree, env=env, timeout=240)
    except subprocess.TimeoutExpired as e:
        # a mutation that makes the tool hang is a finding of its own: report it
        # as red with a telltale, never wait for ever
        return 124, "HUNG after 240s: %s" % ((e.stdout or b"")[-500:] if e.stdout else "")
    return p.returncode, p.stdout + p.stderr


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", nargs="?")
    parser.add_argument("--only")
    args = parser.parse_args()
    only = args.only
    # Audit every pattern BEFORE breaking anything. A mutation whose `old` text no
    # longer exists means the tool moved under this list, and that is a real
    # finding — but asserting it inside the loop stops at the first one and the
    # cases after it never run, so a second stale pattern hides behind the first.
    seen, stale = {}, []
    for label, fname, old, new, _t, _e in M:
        if fname not in seen:
            source = os.path.join(SRC, fname) if fname.startswith("tests/") else os.path.join(BIN, fname)
            with open(source) as f:
                seen[fname] = f.read()
        if apply(seen[fname], old, new) is None:
            stale.append("%s (%s)" % (label, fname))
    if stale:
        print("redphase: %d mutation(s) no longer match the source — the tool moved "
              "under this list, fix these patterns:\n  %s"
              % (len(stale), "\n  ".join(stale)), file=sys.stderr)
        return 2

    root = tempfile.mkdtemp(prefix="c-lean-redphase-")
    green_tree = make_copy(root, "pristine")
    out = []
    try:
        for n, (label, fname, old, new, test, expect) in enumerate(M):
            if only and only not in label and only not in test:
                continue
            tree = make_copy(root, "case%02d" % n)
            path = os.path.join(tree, fname) if fname.startswith("tests/") else os.path.join(tree, "bin", fname)
            src = open(path).read()  # read BEFORE the truncating open
            open(path, "w").write(apply(src, old, new))
            rc, log = run_one(tree, test)
            rc2, log2 = run_one(green_tree, test)
            shutil.rmtree(tree, ignore_errors=True)
            failed = ("FAIL: " + test + " (") in log
            if fname.startswith("tests/"):
                failed = failed or "ERROR: tearDownModule" in log
            rec = {"check": label, "test": test, "red_rc": rc, "red_saw_expected": expect in log,
                   "red_assert": rc == 1 and failed and "AssertionError" in log,
                   "green_unbroken": rc2 == 0,
                   "red_tail": [l[:500] for l in log.splitlines() if l.startswith("AssertionError:")][:2]}
            out.append(rec)
            print(json.dumps(rec, ensure_ascii=False), flush=True)
    finally:
        shutil.rmtree(root, ignore_errors=True)

    bad = [r for r in out if not r["red_assert"] or not r["red_saw_expected"] or not r["green_unbroken"]]
    print("\nRED-PHASE:", len(out) - len(bad), "of", len(out), "clean")
    print("STAYED GREEN:", sum(r["red_rc"] == 0 for r in out))
    if bad:
        print("PROBLEMS:", json.dumps(bad, ensure_ascii=False, indent=1))
    report = args.report or os.path.join(tempfile.mkdtemp(prefix="c-lean-redphase-report-"), "report.json")
    with open(report, "w") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print("report:", report)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
